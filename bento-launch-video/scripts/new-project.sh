#!/bin/sh
# Scaffold a Bento launch video as two HyperFrames projects (16:9 and 9:16)
# from this skill's templates. Usage: new-project.sh <kebab-name> [parent-dir]
set -e
NAME="$1"
PARENT="${2:-$HOME/projects/bento-launch-videos}"
if [ -z "$NAME" ]; then echo "usage: new-project.sh <kebab-name> [parent-dir]" >&2; exit 1; fi
SKILL="$(cd "$(dirname "$0")/.." && pwd)"
WIDE="$PARENT/$NAME"
if [ -e "$WIDE" ]; then echo "$WIDE already exists" >&2; exit 1; fi
mkdir -p "$PARENT"
cd "$PARENT"
npx hyperframes init "$NAME" --non-interactive --example=blank --skill=general-video >/dev/null
cd "$WIDE"
mkdir -p compositions/frames assets .hf-shared renders
cp "$SKILL"/templates/compositions/frames/*.html compositions/frames/
cp "$SKILL"/templates/assets/* assets/
cp "$SKILL"/templates/index.html index.html
cp "$SKILL"/templates/index-vertical.html .hf-shared/index-vertical.html
cp "$SKILL"/templates/sync-vertical.sh sync-vertical.sh
cp "$SKILL"/templates/frame.md frame.md
sed -i '' "s#slack-integration-vertical#${NAME}-vertical#g; s#\"slack-integration\"#\"${NAME}\"#g" sync-vertical.sh
chmod +x sync-vertical.sh
./sync-vertical.sh
echo "Scaffolded:"
echo "  $WIDE            (16:9, edit scenes here)"
echo "  $PARENT/${NAME}-vertical  (9:16, generated by sync-vertical.sh)"
echo "Next: write BRIEF.md and STORYBOARD.md, adapt compositions/frames/*.html, run ./sync-vertical.sh, then npx hyperframes check in both."
